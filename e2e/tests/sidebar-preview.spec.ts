test('profile menu options stay readable on hover and keep the group navigation', async ({ page }) => {
  await register(page, uniqueEmail('profile-menu'))
  await createGroup(page, `Profile Menu ${Date.now()}`)

  for (const theme of ['dark', 'light']) {
    await page.evaluate((value) => window.localStorage.setItem('sonivo:theme', value), theme)
    await page.reload()
    const menu = page.getByTestId('topbar-user-menu')
    await menu.locator('summary').click()
    const groups = menu.getByRole('link', { name: 'Mis grupos', exact: true })
    await groups.hover()
    const contrast = await groups.evaluate((element) => {
      const style = getComputedStyle(element)
      const luminance = (color: string) => {
        const channels = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map((value) => {
          const channel = value / 255
          return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4
        })
        return channels[0] * 0.2126 + channels[1] * 0.7152 + channels[2] * 0.0722
      }
      const foreground = luminance(style.color)
      const background = luminance(style.backgroundColor)
      return (Math.max(foreground, background) + 0.05) / (Math.min(foreground, background) + 0.05)
    })
    expect(contrast).toBeGreaterThanOrEqual(4.5)
    await page.screenshot({ path: `../output/playwright/profile-menu-${theme}.png` })
    await expect(page.getByTestId('group-topbar').getByTestId('group-switcher')).toHaveCount(0)
  }
  await page.getByTestId('topbar-user-menu').getByRole('link', { name: 'Mis grupos', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Mis grupos', exact: true })).toBeVisible()
})

test('group administration stays in the normal navigation and is hidden for members', async ({ page }) => {
  test.setTimeout(120_000)
  await register(page, uniqueEmail('sidebar-owner'))
  await createGroup(page, `Sidebar Admin ${Date.now()}`)
  const navigation = page.getByRole('navigation', { name: 'Grupo', exact: true })
  await expect(navigation.getByRole('link', { name: 'Ajustes del grupo', exact: true })).toHaveCount(1)
  await expect(navigation.getByRole('link', { name: 'Ayuda', exact: true })).toHaveCount(1)
  const labels = (await navigation.getByRole('link').allTextContents()).map((label) => label.trim())
  expect(labels.slice(-3)).toEqual(['Informes', 'Ajustes del grupo', 'Ayuda'])

  const invite = await inviteMemberAndReadLink(page)
  await logout(page)
  await register(page, uniqueEmail('sidebar-member'))
  await page.goto(invite)
  await acceptInvite(page)
  for (const name of ['Administración', 'Informes', 'Ajustes del grupo', 'Ayuda']) {
    await expect(navigation.getByText(name, { exact: true })).toHaveCount(0)
  }
  await expect(navigation.getByRole('link', { name: 'Canciones', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByTestId('mobile-more').locator('summary').click()
  for (const name of ['Informes', 'Ajustes del grupo', 'Ayuda']) {
    await expect(page.getByTestId('mobile-more').getByRole('link', { name, exact: true })).toHaveCount(0)
  }
})
