test('account sidebar previews over the page without moving its content', async ({ page }) => {
  await register(page, uniqueEmail('sidebar-preview'))
  const sidebar = page.getByTestId('app-sidebar')
  const toggle = page.getByTestId('app-sidebar-toggle')
  await expect(sidebar.getByTestId('nav-security')).toHaveAttribute('href', '/app/account/security')
  const accountLinks = (await sidebar.getByRole('navigation').getByRole('link').allTextContents()).map((label) => label.trim())
  expect(accountLinks).toEqual(['Inicio', 'Mis grupos', 'Unirse a grupo', 'Perfil', 'Seguridad', 'Preferencias', 'Notificaciones', 'Membresía', 'Ayuda'])
  const brand = page.getByRole('banner').getByTestId('shell-header-brand')
  await expect(brand).toBeVisible()
  const brandPosition = await brand.boundingBox()
  const searchPosition = await page.getByPlaceholder('Buscar grupos').boundingBox()
  await toggle.click()
  await page.getByRole('main').click({ position: { x: 400, y: 100 } })
  await page.mouse.move(700, 300)
  await expect(sidebar).toHaveAttribute('data-collapsed', 'true')
  await expect.poll(async () => (await sidebar.boundingBox())!.width).toBe(72)
  const compact = await page.getByRole('main').boundingBox()
  expect(await brand.boundingBox()).toEqual(brandPosition)
  expect(await page.getByPlaceholder('Buscar grupos').boundingBox()).toEqual(searchPosition)
  expect((await sidebar.boundingBox())!.y).toBe(64)
  await page.screenshot({ path: '../output/playwright/sidebar-compact.png' })

  await sidebar.hover()
  await expect(sidebar).toHaveAttribute('data-collapsed', 'false')
  expect(await brand.boundingBox()).toEqual(brandPosition)
  await expect.poll(async () => (await sidebar.boundingBox())!.width).toBe(256)
  const preview = await page.getByRole('main').boundingBox()
  expect(preview!.x).toBe(compact!.x)
  expect(preview!.width).toBe(compact!.width)
  await page.screenshot({ path: '../output/playwright/sidebar-preview.png' })

  await page.mouse.move(700, 300)
  await expect(sidebar).toHaveAttribute('data-collapsed', 'true')
  await page.keyboard.press('Tab')
  await sidebar.getByTestId('nav-home').focus()
  await expect(sidebar).toHaveAttribute('data-collapsed', 'false')
  await page.keyboard.press('Escape')
  await expect(sidebar).toHaveAttribute('data-collapsed', 'true')
  await toggle.press('Enter')
  await expect(sidebar).toHaveAttribute('data-pinned', 'true')
  await expect.poll(async () => (await page.getByRole('main').boundingBox())!.x).toBe(256)
  await page.reload()
  await expect(toggle).toHaveAccessibleName('Contraer menú lateral')
  await page.screenshot({ path: '../output/playwright/sidebar-pinned.png' })
})

test('group sidebar overlays without resizing the workspace and remembers the compact preference', async ({ page }) => {
  await register(page, uniqueEmail('sidebar-group'))
  await createGroup(page, `Sidebar Band ${Date.now()}`)
  const sidebar = page.getByTestId('group-rail')
  const toggle = page.getByTestId('rail-collapse-toggle')
  const brand = page.getByRole('banner').getByTestId('rail-brand')
  const brandPosition = await brand.boundingBox()
  const searchPosition = await page.getByTestId('group-search').boundingBox()
  await toggle.click()
  await page.mouse.move(700, 300)
  await expect.poll(async () => (await sidebar.boundingBox())!.width).toBe(72)
  expect(await brand.boundingBox()).toEqual(brandPosition)
  expect(await page.getByTestId('group-search').boundingBox()).toEqual(searchPosition)
  expect((await sidebar.boundingBox())!.y).toBe(64)
  for (const abbreviation of ['RE', 'MÚ', 'AG', 'EQ', 'AD']) {
    const marker = sidebar.getByText(abbreviation, { exact: true })
    await expect(marker).toHaveCSS('opacity', '1')
    const bounds = await marker.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(72)
  }
  const content = page.getByTestId('group-content-scroll')
  const compact = await content.boundingBox()
  await page.screenshot({ path: '../output/playwright/group-sidebar-compact.png' })
  const songs = sidebar.getByRole('link', { name: 'Canciones', exact: true })
  const iconPosition = await songs.locator('svg').boundingBox()
  await sidebar.hover()
  await expect.poll(async () => (await sidebar.boundingBox())!.width).toBe(240)
  await expect(sidebar.getByText('MÚ', { exact: true })).toHaveCSS('opacity', '0')
  await expect(sidebar.getByText('Música', { exact: true })).toHaveCSS('opacity', '1')
  expect((await content.boundingBox())!.x).toBe(compact!.x)
  expect((await content.boundingBox())!.width).toBe(compact!.width)
  expect((await songs.locator('svg').boundingBox())!.y).toBe(iconPosition!.y)
  await page.screenshot({ path: '../output/playwright/group-sidebar-preview.png' })
  await page.mouse.move(700, 300)
  await page.reload()
  await expect(sidebar).toHaveAttribute('data-pinned', 'false')
  await songs.click()
  await expect(page.getByRole('heading', { name: 'Canciones', exact: true })).toBeVisible()

  await page.setViewportSize({ width: 390, height: 844 })
  await expect(sidebar).not.toBeVisible()
  await expect(page.getByTestId('mobile-tabbar')).toHaveCount(0)
  const quickNavigation = page.getByTestId('mobile-section-nav')
  await expect(quickNavigation).toBeVisible()
  await expect(page.getByTestId('group-topbar').getByTestId('rail-brand')).toBeVisible()
  const groupPath = new URL(page.url()).pathname.replace(/\/library$/, '')
  await expect(page.getByTestId('group-calendar')).toHaveAttribute('href', `${groupPath}/calendar`)
  await page.setViewportSize({ width: 320, height: 844 })
  const mobileBrandBounds = await page.getByTestId('rail-brand').boundingBox()
  expect(mobileBrandBounds!.x + mobileBrandBounds!.width).toBeLessThanOrEqual((await page.getByTestId('group-mobile-search-toggle').boundingBox())!.x)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await page.setViewportSize({ width: 390, height: 844 })
  const headerBounds = await page.getByTestId('group-topbar').boundingBox()
  const searchToggle = page.getByTestId('group-mobile-search-toggle')
  await searchToggle.click()
  await expect(page.getByTestId('search-backdrop')).toBeVisible()
  expect((await page.getByTestId('search-backdrop').boundingBox())!.y).toBe(headerBounds!.y + headerBounds!.height)
  await expect(quickNavigation).not.toBeVisible()
  await expect(page.getByTestId('group-search')).toBeFocused()
  expect((await page.getByTestId('group-topbar').boundingBox())!.height).toBe(headerBounds!.height)
  await page.screenshot({ path: '../output/playwright/mobile-search-focused.png' })
  await page.getByTestId('group-search').press('Escape')
  await expect(searchToggle).toBeFocused()
  await expect(quickNavigation).toBeVisible()
  await expect(page.getByTestId('search-backdrop')).toHaveCount(0)
  await expect(page.getByTestId('group-search')).not.toBeVisible()
  await page.getByTestId('group-notifications-bell').click()
  const inbox = page.getByTestId('group-notifications-panel')
  await expect(inbox).toBeVisible()
  await expect(page.getByTestId('notifications-backdrop')).toBeVisible()
  expect((await page.getByTestId('notifications-backdrop').boundingBox())!.y).toBe(headerBounds!.y + headerBounds!.height)
  await page.screenshot({ path: '../output/playwright/mobile-notifications-focused.png' })
  const inboxBounds = await inbox.boundingBox()
  expect(inboxBounds!.x).toBeGreaterThanOrEqual(0)
  expect(inboxBounds!.x + inboxBounds!.width).toBeLessThanOrEqual(390)
  await page.getByTestId('group-notifications-bell').press('Escape')
  await expect(page.getByTestId('notifications-backdrop')).toHaveCount(0)
  await quickNavigation.getByRole('link', { name: 'Listas', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Listas', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: '../output/playwright/sidebar-mobile.png' })
})

