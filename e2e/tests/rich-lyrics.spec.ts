import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'
import { createArrangement, createFileResource, createGroup, createSong, exportArrangementLyrics, openArrangementEditor, openLibrary, openLyricsImportDialog, openPractice, openSong, register, returnToArrangement, uniqueEmail } from './helpers'

test('owner imports TTML, exports Sonivo format and follows simultaneous vocals on desktop and mobile', async ({ page, request }, testInfo) => {
  test.setTimeout(120_000)
  const flags = await (await request.get('/api/features')).json()
  test.skip(!flags.lrc || !flags.stageMode, 'Rich lyrics requires Features:Lrc and Features:StageMode')
  const songTitle = `An original morning ${Date.now()}`
  await page.setViewportSize({ width: 1440, height: 900 })
  await register(page, uniqueEmail('rich-lyrics'))
  await createGroup(page, `Lyrics ${Date.now()}`)
  await openLibrary(page)
  await createSong(page, songTitle)
  await openSong(page, songTitle)
  await createArrangement(page, 'Morning session')
  await createFileResource(page, { label: 'Original reference', purpose: 'audio', filePath: path.join(path.dirname(fileURLToPath(import.meta.url)), 'fixtures', 'practice-a.wav') })
  await openArrangementEditor(page, 'lyrics')
  await expect(page.getByTestId('chordpro-digitizer')).toBeVisible()

  const panel = await openLyricsImportDialog(page)
  await expect(page.getByRole('button', { name: 'Descargar TTML de Sonivo' })).toHaveCount(0)
  await panel.getByRole('button', { name: 'Pegar texto' }).click()
  await panel.getByLabel('Pegar letras o contenido del proveedor').fill('<tt xmlns="http://www.w3.org/ns/ttml"><body><div><p begin="00:00.100" end="00:01.500">Que un <span begin="00:00.100" end="00:00.800">día</span></p><p begin="00:00.300" end="00:00.900"><span begin="00:00.300" end="00:00.900">(Oh)</span></p><p begin="00:02.000" end="00:02.800"><span begin="00:02.000" end="00:02.200">We</span> keep <span begin="00:02.400" end="00:02.800">rising</span></p></div></body></tt>')
  const previewResponse = page.waitForResponse(response => response.url().includes('/lyrics/import-lrc'))
  await panel.getByRole('button', { name: 'Revisar importación' }).click()
  const preview = await (await previewResponse).json()
  expect(preview.wordCount).toBe(4)
  expect(preview.errors).toEqual([])
  await panel.getByRole('button', { name: 'Añadir al borrador' }).click()
  await expect(panel.getByRole('button', { name: 'Añadir al borrador' })).toBeHidden()
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(page.getByTestId('chordpro-digitizer')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Descargar TTML de Sonivo' })).toHaveCount(0)
  await returnToArrangement(page)
  expect(await exportArrangementLyrics(page, 'ttml')).toContain('sonivo:version="1"')
  await openPractice(page)
  const globalPlayer = page.getByTestId('global-player')
  await expect(globalPlayer).toBeVisible()
  await globalPlayer.locator('[data-player-expand]:visible').first().click()
  const fullPlayer = page.getByTestId('global-player-fullscreen')
  await expect(fullPlayer).toBeVisible()
  await expect(fullPlayer.locator('[data-lyric-line-seek]')).toHaveCount(3)
  await expect(fullPlayer.locator('[data-lyric-line-seek] button')).toHaveCount(0)
  const playerSeek = fullPlayer.getByRole('slider', { name: 'Progreso de reproducción de audio' })
  await playerSeek.evaluate(element => {
    const input = element as HTMLInputElement
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, '2.3')
    input.dispatchEvent(new Event('input', { bubbles: true }))
    input.dispatchEvent(new Event('change', { bubbles: true }))
  })
  await expect(fullPlayer.locator('[data-active="true"]')).toContainText('We')
  const previousLyricLine = fullPlayer.locator('[data-lyric-line-row="0"]')
  await expect.poll(() => previousLyricLine.evaluate(element => getComputedStyle(element).filter)).toMatch(/blur\((?!0px\))/)
  await page.setViewportSize({ width: 390, height: 844 })
  await fullPlayer.getByRole('button', { name: 'Letra', exact: true }).click()
  const mobileLyrics = fullPlayer.locator('[data-player-scrollable][data-player-lyrics-scrollable]:visible').first()
  await expect(mobileLyrics).toHaveCSS('padding-top', '0px')
  await expect(mobileLyrics).toHaveCSS('padding-bottom', '0px')
  await page.keyboard.press('Escape')
  await expect(fullPlayer).toBeHidden()
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByTestId('stage-open').click()
  const stage = page.getByTestId('stage-mode')
  await expect(stage).toBeVisible()
  await expect(stage.getByTestId('stage-seek')).toBeVisible()
  const lyricsBounds = await stage.getByTestId('stage-scroll').boundingBox()
  const desktopPlayerBounds = await stage.getByTestId('stage-seek').boundingBox()
  expect(lyricsBounds).not.toBeNull()
  expect(desktopPlayerBounds).not.toBeNull()
  expect(desktopPlayerBounds!.y).toBeGreaterThan(lyricsBounds!.y + lyricsBounds!.height - 1)
  await stage.getByTestId('stage-seek').evaluate(element => {
    const input = element as HTMLInputElement
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, '0.5')
    input.dispatchEvent(new Event('input', { bubbles: true }))
    input.dispatchEvent(new Event('change', { bubbles: true }))
  })
  await expect(stage.locator('[data-active-line="true"]')).toHaveCount(2)
  const lead = stage.locator('[data-stage-line="0"]')
  const backing = stage.locator('[data-stage-line="1"]')
  await expect(backing).toHaveAttribute('data-backing-vocal', 'true')
  expect(await backing.evaluate(element => Number.parseFloat(getComputedStyle(element).fontSize))).toBeLessThan(
    await lead.evaluate(element => Number.parseFloat(getComputedStyle(element).fontSize)),
  )
  await expect(lead).toHaveCSS('opacity', '1')
  await expect(stage.locator('[data-stage-line="0"] [data-word-progress]')).toHaveAttribute('data-word-progress', '0.571')
  await expect(stage.locator('[data-stage-line="1"] [data-word-progress]')).toHaveAttribute('data-word-progress', '0.333')
  await expect(stage.locator('[data-stage-line="0"] [data-word-progress]')).toHaveCSS('background-image', /linear-gradient/)
  await expect(stage.locator('[data-stage-line="0"] [data-word-progress]')).toHaveCSS('filter', /drop-shadow/)
  await expect(stage.locator('[data-stage-line="0"] [data-stage-word="0"]')).toHaveAttribute('data-word-completed', 'true')
  await expect(stage.locator('[data-stage-line="0"] [data-stage-word="1"]')).toHaveAttribute('data-word-completed', 'true')
  const futureLine = stage.locator('[data-stage-line="2"]')
  await futureLine.hover()
  await expect(futureLine).toHaveCSS('filter', 'blur(0px)')
  await expect(futureLine).toHaveCSS('opacity', '1')
  await expect(futureLine).not.toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await stage.getByTestId('stage-seek').hover()
  await expect.poll(() => futureLine.evaluate(element => getComputedStyle(element).filter)).not.toBe('blur(0px)')
  await stage.getByTestId('stage-seek').evaluate(element => {
    const input = element as HTMLInputElement
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, '2.3')
    input.dispatchEvent(new Event('input', { bubbles: true }))
    input.dispatchEvent(new Event('change', { bubbles: true }))
  })
  const interpolatedWord = stage.locator('[data-stage-line="2"] [data-stage-word="1"]')
  await expect.poll(async () => Number(await interpolatedWord.getAttribute('data-word-progress'))).toBeGreaterThan(0.4)
  await expect.poll(async () => Number(await interpolatedWord.getAttribute('data-word-progress'))).toBeLessThan(0.6)
  await stage.getByTestId('stage-seek').evaluate(element => {
    const input = element as HTMLInputElement
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, '0.2')
    input.dispatchEvent(new Event('input', { bubbles: true }))
    input.dispatchEvent(new Event('change', { bubbles: true }))
  })
  await expect(stage.locator('[data-stage-line="0"] [data-stage-word="2"]')).toHaveAttribute('data-word-progress', /0\./)
  await stage.getByTestId('stage-play-pause-desktop').click()
  await expect(stage.getByTestId('stage-play-pause-desktop')).toHaveAttribute('aria-label', 'Pausar')
  await page.evaluate(() => {
    const audio = document.querySelector('audio')!
    const samples: Array<{ updates: number; progress: number }> = []
    let updates = 0
    audio.addEventListener('timeupdate', () => updates++)
    const sample = () => {
      const progress = Number(document.querySelector('[data-stage-line="0"] [data-stage-word="2"]')?.getAttribute('data-word-progress'))
      samples.push({ updates, progress })
      if (samples.length < 24) requestAnimationFrame(sample)
      else (window as Window & { __lyricProgressSamples?: typeof samples }).__lyricProgressSamples = samples
    }
    requestAnimationFrame(sample)
  })
  await expect.poll(() => page.evaluate(() => (window as Window & { __lyricProgressSamples?: unknown[] }).__lyricProgressSamples?.length ?? 0)).toBe(24)
  const progressSamples = await page.evaluate(() => (window as Window & { __lyricProgressSamples?: Array<{ updates: number; progress: number }> }).__lyricProgressSamples ?? [])
  expect(progressSamples.some((sample, index) => index > 0 && sample.updates === progressSamples[index - 1]!.updates &&
    Number.isFinite(sample.progress) && sample.progress - progressSamples[index - 1]!.progress > 0.005)).toBeTruthy()
  await stage.getByTestId('stage-play-pause-desktop').click()
  const wordGap = await stage.locator('[data-stage-line="0"]').evaluate(line => {
    const first = line.querySelector('[data-stage-word="0"]')!.getBoundingClientRect()
    const second = line.querySelector('[data-stage-word="1"]')!.getBoundingClientRect()
    return second.left - first.right
  })
  expect(wordGap).toBeGreaterThan(3)
  await page.screenshot({ path: testInfo.outputPath('lyrics-desktop.png') })
  const follow = stage.getByTestId('stage-follow')
  await lead.dispatchEvent('pointerdown', { pointerId: 1, pointerType: 'mouse', isPrimary: true, button: 0, buttons: 1 })
  await expect(follow).toHaveAttribute('aria-pressed', 'true')
  await stage.getByTestId('stage-scroll').hover()
  await page.mouse.wheel(0, 300)
  await expect(follow).toHaveAttribute('aria-pressed', 'false')
  await follow.click()
  await expect(follow).toHaveAttribute('aria-pressed', 'true')
  await page.evaluate(async () => { if (document.fullscreenElement) await document.exitFullscreen() })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(stage).toBeVisible()
  expect(await stage.evaluate(element => element.scrollWidth <= element.clientWidth)).toBeTruthy()
  const mobileLyricsBounds = await stage.getByTestId('stage-scroll').boundingBox()
  const mobilePlayerBounds = await stage.getByTestId('stage-seek').boundingBox()
  expect(mobileLyricsBounds).not.toBeNull()
  expect(mobilePlayerBounds).not.toBeNull()
  expect(mobilePlayerBounds!.y).toBeGreaterThan(mobileLyricsBounds!.y + mobileLyricsBounds!.height - 1)
  await page.screenshot({ path: testInfo.outputPath('lyrics-mobile.png') })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(stage.locator('[data-stage-line="2"]')).toHaveCSS('filter', 'none')
  await stage.getByRole('button', { name: 'Ir a «We» en la canción' }).click()
  await expect(stage.locator('[data-stage-line="2"][data-active-line="true"]')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(stage).toBeHidden()
})

test('owner searches synced lyrics by title and selects a recording for review', async ({ page, request }) => {
  test.setTimeout(120_000)
  const flags = await (await request.get('/api/features')).json()
  test.skip(!flags.lrc, 'Lyrics lookup requires Features:Lrc')
  const songTitle = `Title lookup ${Date.now()}`
  await register(page, uniqueEmail('lyrics-search'))
  await createGroup(page, `Lyrics lookup ${Date.now()}`)
  await openLibrary(page)
  await createSong(page, songTitle)
  await openSong(page, songTitle)
  await createArrangement(page, 'Search session')
  await openArrangementEditor(page, 'lyrics')
  await expect(page.getByTestId('chordpro-digitizer')).toBeVisible()
  const panel = await openLyricsImportDialog(page)
  await expect(panel.getByRole('button', { name: 'Archivo' })).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Pegar texto' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Descargar TTML de Sonivo' })).toHaveCount(0)
  await page.route('**/lyrics/lookup', async (route) => route.fulfill({
    status: 200,
    contentType: 'application/json',
    body: JSON.stringify([
      { source: 'LRCLIB', recordId: 101, title: 'Title lookup', artist: 'Artist One', album: 'First album', duration: 120, content: '[00:01.00]First synced result' },
      { source: 'LRCLIB', recordId: 102, title: 'Title lookup', artist: 'Artist Two', album: 'Second album', duration: 135, content: '[00:01.00]Second synced result' },
    ]),
  }))
  await panel.getByRole('button', { name: 'Buscar', exact: true }).click()
  const lookupDialog = panel
  await lookupDialog.getByLabel('Título de la grabación').fill('Title lookup')
  const lookupResponse = page.waitForResponse(response => response.url().includes('/lyrics/lookup'))
  await lookupDialog.getByRole('button', { name: 'Buscar letra' }).click()
  const lookup = await lookupResponse
  expect(lookup.status()).toBe(200)
  expect(lookup.request().postDataJSON()).toEqual({ title: 'Title lookup' })
  await expect(lookupDialog.getByRole('region', { name: 'Grabaciones encontradas' })).toBeVisible()
  await expect(lookupDialog.getByRole('heading', { name: 'Title lookup' })).toHaveCount(2)
  const secondResult = lookupDialog.locator('article').filter({ hasText: 'Artist Two' })
  await secondResult.getByRole('button', { name: 'Usar esta letra' }).click()
  await expect(lookupDialog).toBeVisible()
  await expect(panel.getByLabel('Pegar letras o contenido del proveedor')).toHaveValue('[00:01.00]Second synced result')
  await panel.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(lookupDialog.getByLabel('Título de la grabación')).toHaveValue('Title lookup')
  await expect(lookupDialog.getByRole('region', { name: 'Grabaciones encontradas' })).toBeVisible()
  await expect(lookupDialog.getByRole('heading', { name: 'Title lookup' })).toHaveCount(2)

})
